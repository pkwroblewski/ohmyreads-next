const PART_SEPARATOR = /\s*(?:,|\/|--|;)\s*/;

/** Lower-case, single-spaced, straight apostrophes, no trailing full stop. */
export function genreKey(part: string): string {
  return part
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\.$/, "")
    .toLowerCase();
}

/**
 * Map raw genre strings from any source onto the vocabulary, in first-seen
 * order and without duplicates. Unknown strings are dropped, so the result
 * may be empty — callers decide what an empty list means for them.
 */
export function normalizeGenres(raw: readonly (string | null | undefined)[]): Genre[] {
  const out: Genre[] = [];
  for (const value of raw) {
    if (!value) continue;
    for (const part of value.split(PART_SEPARATOR)) {
      const hits = GENRE_ALIASES[genreKey(part)];
      if (!hits) continue;
      for (const genre of hits) if (!out.includes(genre)) out.push(genre);
    }
  }
  return out;
}

export function isGenre(value: string): value is Genre {
  return (GENRE_VOCABULARY as readonly string[]).includes(value);
}

/** `(variant, canonical[])` rows for the SQL alias table in migration 072. */
export function genreAliasRows(): Array<[string, readonly Genre[]]> {
  return Object.entries(GENRE_ALIASES);
}
