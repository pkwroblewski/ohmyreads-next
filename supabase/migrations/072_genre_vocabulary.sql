parts AS (
  SELECT b.id, g.ord AS gord, p.ord AS pord,
         lower(regexp_replace(btrim(regexp_replace(translate(p.part, '’‘', ''''''), '\s+', ' ', 'g')), '\.$', '')) AS key
  FROM public.books b
  CROSS JOIN LATERAL unnest(b.genres) WITH ORDINALITY g(genre, ord)
  CROSS JOIN LATERAL regexp_split_to_table(g.genre, '\s*(,|/|--|;)\s*') WITH ORDINALITY p(part, ord)
),
hits AS (
  SELECT p.id, c.genre, min(p.gord * 1000000 + p.pord * 1000 + c.ord) AS pos
  FROM parts p
  JOIN alias a ON a.variant = p.key
  CROSS JOIN LATERAL unnest(a.canonical) WITH ORDINALITY c(genre, ord)
  GROUP BY p.id, c.genre
),
mapped AS (
  SELECT id, array_agg(genre ORDER BY pos) AS genres FROM hits GROUP BY id
)
UPDATE public.books b
SET genres = m.genres
FROM mapped m
WHERE m.id = b.id
  AND b.genres IS DISTINCT FROM m.genres;

-- Part 2: Browse chips ordered by book count --------------------------------

CREATE OR REPLACE FUNCTION public.get_distinct_genres()
RETURNS TABLE(genre text)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT g AS genre
  FROM public.books, unnest(genres) AS g
  GROUP BY g
  ORDER BY count(*) DESC, g;
$$;

-- Check: distinct genre strings left (expected ~51) and rows with no genre (expected 0)
SELECT
  (SELECT count(DISTINCT g) FROM public.books, unnest(genres) g) AS distinct_genres,
  (SELECT count(*) FROM public.books WHERE genres IS NULL OR cardinality(genres) = 0) AS empty_rows;
