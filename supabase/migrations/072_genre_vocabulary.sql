-- ============================================
-- Migration 072: genre vocabulary clean-up
--
-- Catalog launch plan (2026-09-05) task 8. After the NYT / Open Library
-- imports `books.genres` held 7,141 distinct strings — Open Library subjects
-- and Google categories leaked through ("Fiction, Thrillers, General",
-- "Juvenile Fiction", "[document]", "11.93 Buddhism", "1835-1910") — and the
-- Browse page listed every one of them as a filter chip.
--
-- Part 1 rewrites every row's `genres` through the alias table below, which
-- is generated from `GENRE_ALIASES` in lib/data/genres.ts (the same mapping
-- every importer and the search-to-add action now apply on the way in).
-- Each string is split on `,` `/` `--` `;`, every part is looked up
-- case-insensitively, unknown parts are dropped, first-seen order is kept and
-- duplicates collapse. A row that would end up empty keeps what it had (the
-- 2026-09-07 dry run found none). Idempotent: vocabulary entries map onto
-- themselves.
--
-- Part 2 makes get_distinct_genres() (the Browse chip list, migration 047)
-- return genres by book count instead of alphabetically, so the first row of
-- chips is the biggest genres.
--
-- Usage:
--   npx supabase db query --linked -f supabase/migrations/072_genre_vocabulary.sql
-- ============================================

